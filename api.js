// All three fetchers hit static JSON on the same host, so they should be fast —
// but a hanging host used to leave the page on the spinner forever. 10s cap:
// on timeout each falls through to its existing graceful-degradation path.
function fetchWithTimeout(url, ms = 10000) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), ms);
  return fetch(url, { signal: ctrl.signal }).finally(() => clearTimeout(timer));
}

async function fetchRepsIndex() {
  try {
    const res = await fetchWithTimeout('data/reps-index.json');
    if (!res.ok) return {};
    return await res.json();
  } catch (e) { return {}; }
}

// bioguide -> /rep/<slug>/ , so client-rendered member links can point at the
// static profile instead of the rep.html?id= redirector. Website-only file
// (built for that redirector); an empty map just keeps the redirector links.
async function fetchRepSlugs() {
  try {
    // Root-absolute: the generated /bill/<slug>/ pages load this set from two
    // levels deep, where a relative 'data/...' would 404 (same reason bill.js
    // uses /data/ paths).
    const res = await fetchWithTimeout('/data/rep-slug-index.json');
    if (!res.ok) return {};
    return await res.json();
  } catch (e) { return {}; }
}

async function fetchStandaloneQuotes() {
  try {
    const res = await fetchWithTimeout('data/quotes.json');
    if (!res.ok) return [];
    const data = await res.json();
    return data.quotes || [];
  } catch (e) { return []; }
}

// Reads from static data/cache.json generated by the batch processor. On ANY
// failure (404, empty, unparseable, > 10 s) it throws, and the caller shows its
// honest error state («couldn't load bills» + Try again). It used to return
// a demo-bill fallback: 3 invented bills with invented quotes attributed to real
// senators (HOTFIX-REAL-PEOPLE-2, 2026-10-26; scripts/test-no-placeholder-quotes.js).
const BILLS_LOAD_ERROR = "Couldn't load bills right now. Check your connection and try again.";
async function fetchRecentBills() {
  let data;
  try {
    const res = await fetchWithTimeout('data/cache.json');
    if (!res.ok) throw new Error('HTTP ' + res.status);
    data = await res.json();
  } catch (e) {
    console.warn('Failed to load data/cache.json', e);
    throw new Error(BILLS_LOAD_ERROR);
  }
  if (!data || !Array.isArray(data.bills) || data.bills.length === 0) {
    console.warn('data/cache.json has no bills');
    throw new Error(BILLS_LOAD_ERROR);
  }
  return data.bills;
}

function detectStage(bill, actions) {
  // Walk actions newest-first to find current stage
  const sorted = [...actions].sort((a,b) => new Date(b.actionDate) - new Date(a.actionDate));
  for (const action of sorted) {
    const text = (action.text || '').toLowerCase();
    const type = (action.type || '').toLowerCase();
    if (text.includes('vetoed by president') || text.includes('pocket veto') ||
        (text.includes('returned to') && text.includes('with objections')))
      return { key: 'vetoed', label: 'Vetoed' };
    if (text.includes('signed by president') || text.includes('became public law'))
      return { key: 'signed', label: 'Signed into law' };
    if (text.includes('passed senate') || text.includes('senate passed'))
      return { key: 'senate', label: 'Senate passed' };
    if (text.includes('passed house') || text.includes('house passed'))
      return { key: 'house', label: 'House passed' };
    if (text.includes('senate') && (text.includes('committee') || text.includes('referred')))
      return { key: 'committee', label: 'Senate committee' };
    if (text.includes('house') && (text.includes('committee') || text.includes('referred')))
      return { key: 'committee', label: 'House committee' };
    if (text.includes('conference'))
      return { key: 'conference', label: 'Conference' };
  }
  return { key: 'introduced', label: 'Introduced' };
}

function buildPipeline(bill, actions) {
  const steps = ['Introduced', 'Committee', 'House floor', 'Senate floor', 'Conference', 'Signed'];
  const stageOrder = { introduced: 0, committee: 1, house: 2, senate: 3, conference: 4, signed: 5, vetoed: 5 };
  const stage = detectStage(bill, actions);
  const currentIndex = stageOrder[stage.key] ?? 0;
  return { steps, currentIndex };
}

function estimateLikelihood(stageKey, bill, actions) {
  // Simple heuristic — in production you'd use vote counts, co-sponsor counts, etc.
  const base = { introduced: 12, committee: 28, house: 52, senate: 68, conference: 82, signed: 100, vetoed: 0 };
  let pct = base[stageKey] || 10;
  // More co-sponsors = slightly higher likelihood
  const cosponsors = bill.cosponsors?.count || 0;
  if (cosponsors > 50) pct = Math.min(pct + 10, 95);
  else if (cosponsors > 20) pct = Math.min(pct + 5, 95);
  return pct;
}

function formatSponsor(sponsor) {
  if (!sponsor) return 'Unknown sponsor';
  const party = sponsor.party ? `(${sponsor.party})` : '';
  const state = sponsor.state || '';
  return `${sponsor.fullName || sponsor.name || 'Unknown'} ${party} ${state}`.trim();
}

