#!/usr/bin/env node
// check-conflict-markers.js — refuse to commit an unresolved merge.
//
//   node scripts/check-conflict-markers.js              (scan the STAGED content — pre-commit)
//   node scripts/check-conflict-markers.js --tree       (scan every tracked file — CI / audit)
//   node scripts/check-conflict-markers.js --self-test  (prove the detector has teeth)
//
// WHY THIS EXISTS. On 2026-09-01 a merge left literal "<<<<<<< HEAD" /
// "=======" / ">>>>>>> <branch>" lines inside THREE committed JSON sidecars —
// data/article-date-state.json, data/link-check-cache.json and
// data/qa-provenance.json — and they survived three commits before anyone
// noticed (they were finally stripped in 40720664, ca2b305e and a672a5b1).
//
// Every one of the six existing pre-commit gates read straight past them:
//   - security-check.js scans for secrets and unsafe markup, not syntax;
//   - validate-batch.js parses data/cache.json, which was not one of the three;
//   - qa-regression and qa-receipts read the LEDGERS, not the sidecars;
//   - preflight parses the rendered pages;
//   - the generated-surface check compares regenerated output, and all three
//     files are regenerated by scripts that overwrite rather than merge.
// A corrupt JSON sidecar therefore fails SILENTLY at read time — every reader
// in this repo wraps its JSON.parse in a try/catch that falls back to `{}` or
// `[]` (readJsonSafe, readJson(p, fb)), which is exactly why nothing screamed.
// So the defect class needs a gate that looks at the raw bytes and cares about
// nothing else.
//
// PRECISION. Git writes markers as EXACTLY seven characters at the start of a
// line: "<<<<<<< label", "=======", ">>>>>>> label", and (in diff3 style)
// "||||||| label". Stored source text in data/ref-text/ is full of long "="
// rules — 60 and 71 characters — so the pattern anchors on exactly seven and
// requires the line to end there or continue with a space. Verified against the
// whole tracked tree at authoring time: ZERO matches, so the gate needs no
// exemption list, and any future match is a real unresolved merge.
//
// Reads:  the git index (or the tree with --tree). Writes: nothing.
// Exit:   0 clean · 1 markers found (or a self-test failure).

'use strict';

const { execFileSync } = require('child_process');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const args = process.argv.slice(2);
const flag = (n) => args.includes('--' + n);
const TREE = flag('tree');
const SELFTEST = flag('self-test');

// Built from a count so this file cannot trip its own gate, and so the four
// forms stay visibly parallel. `(?: .*)?$` accepts git's label suffix.
// The character is regex-escaped: the diff3 base marker is "|", which unescaped
// would compile to seven empty alternations and match EVERY line — caught by
// the self-test below on the first run, which is what the self-test is for.
const M = (ch) => new RegExp('^(?:\\' + ch + '){7}(?: .*)?$');
const PATTERNS = [
    { name: 'ours',   re: M('<') },
    { name: 'base',   re: M('|') },
    { name: 'split',  re: M('=') },
    { name: 'theirs', re: M('>') },
];

/** Lines in `text` that are a git conflict marker. Returns [{ line, name, text }]. */
function scan(text) {
    const out = [];
    const lines = text.split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
        for (const p of PATTERNS) {
            if (p.re.test(lines[i])) { out.push({ line: i + 1, name: p.name, text: lines[i] }); break; }
        }
    }
    return out;
}

function git(argv) {
    return execFileSync('git', argv, { cwd: ROOT, encoding: 'utf8', maxBuffer: 512 * 1024 * 1024, windowsHide: true });
}

/**
 * The files to inspect, and their content.
 * Pre-commit mode reads the STAGED blob, not the worktree file: the worktree may
 * already be fixed while the resolved-looking commit still carries the markers.
 */
function subjects() {
    if (TREE) {
        const names = git(['ls-files', '-z']).split('\0').filter(Boolean);
        return names.map((f) => ({ file: f, read: () => git(['show', `HEAD:${f}`]) }));
    }
    // A = added, C = copied, M = modified, R = renamed. Deletions have no content.
    const names = git(['diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z'])
        .split('\0').filter(Boolean);
    return names.map((f) => ({ file: f, read: () => git(['show', `:${f}`]) }));
}

function run() {
    let checked = 0;
    const hits = [];
    for (const s of subjects()) {
        let text;
        try { text = s.read(); } catch (e) { continue; }   // binary / unreadable blob
        if (text.indexOf('\0') >= 0) continue;             // binary
        checked++;
        for (const h of scan(text)) hits.push({ file: s.file, ...h });
    }

    if (hits.length) {
        console.log(`\n  ❌ ${hits.length} unresolved merge-conflict marker(s) in ${new Set(hits.map(h => h.file)).size} file(s):\n`);
        for (const h of hits.slice(0, 40)) {
            console.log(`     ${h.file}:${h.line}  ${h.text.slice(0, 60)}`);
        }
        if (hits.length > 40) console.log(`     … and ${hits.length - 40} more`);
        console.log('\n     Resolve the merge before committing. A marker inside a JSON sidecar');
        console.log('     does not throw — every reader here falls back to an empty object, so');
        console.log('     the corruption is silent. There is no bypass for this gate.\n');
        return 1;
    }
    console.log(`  ✅ no merge-conflict markers (${checked} ${TREE ? 'tracked' : 'staged'} file(s) scanned)`);
    return 0;
}

// ── Self-test: the detector must fire on real markers and stay silent on the
// long "=" rules that stored source text legitimately contains. ──────────────
function selfTest() {
    const cases = [
        // [label, text, expected marker count]
        ['git conflict, merge style', '{\n<<<<<<< HEAD\n  "a": 1\n=======\n  "a": 2\n>>>>>>> dev\n}\n', 3],
        ['git conflict, diff3 style', '<<<<<<< ours\nx\n||||||| base\ny\n=======\nz\n>>>>>>> theirs\n', 4],
        ['bare marker, no label',     '<<<<<<<\n=======\n>>>>>>>\n', 3],
        ['CRLF line endings',         '<<<<<<< HEAD\r\n=======\r\n>>>>>>> dev\r\n', 3],
        ['60-char rule (ref-text)',   '='.repeat(60) + '\n', 0],
        ['71-char rule (ref-text)',   '='.repeat(71) + '\n', 0],
        ['6 chars is not a marker',   '======\n<<<<<<\n>>>>>>\n', 0],
        ['8 chars is not a marker',   '========\n<<<<<<<<\n>>>>>>>>\n', 0],
        ['marker not at line start',  '  <<<<<<< HEAD\nfoo =======\n', 0],
        ['prose about a marker',      'The merge left a <<<<<<< HEAD line in the file.\n', 0],
        ['clean json',                '{\n  "a": 1\n}\n', 0],
    ];
    let failed = 0;
    for (const [label, text, want] of cases) {
        const got = scan(text).length;
        const ok = got === want;
        if (!ok) failed++;
        console.log(`  ${ok ? '✅' : '❌'} ${label}: expected ${want}, got ${got}`);
    }
    console.log('');
    if (failed) { console.log(`  ❌ conflict-marker self-test: ${failed} case(s) failed`); return 1; }
    console.log(`  ✅ conflict-marker self-test: ${cases.length}/${cases.length} cases pass`);
    return 0;
}

process.exit(SELFTEST ? selfTest() : run());
