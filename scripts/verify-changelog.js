#!/usr/bin/env node
// verify-changelog.js -- cross-check every published changelog edition against
// the current bill record.
//
// WHY: a changelog edition is generated once and never regenerated, so it
// freezes whatever the bill was called that day. When a chamber substitutes a
// bill's text the TITLE changes -- and the frozen edition then misidentifies the
// bill to readers, and links to a slug that no longer exists.
//
// Found on first run: the 2026-08-12 edition calls H.R. 5334 the "Supporting
// Early-childhood Educators' Deductions Act of 2025". It is now the "Lindsey O.
// Graham Sanctioning Russia and Iran Act of 2026" -- a completely different
// bill by subject.
//
// Checks per entry: bill resolves; title matches the current title; the claimed
// destination stage matches the recorded stage; the bill link resolves on disk.
// Also cross-checks every count the page states about itself -- the subline
// ("N advanced a stage · M new to the site") and each group header -- against
// the entries actually listed.
//
// COVERAGE (the 2026-08-13 hardening pass): this walked only changelog/<date>/
// directories, so changelog/index.html -- the hub, the page readers actually
// land on -- was never checked. It embeds the latest edition in full and is
// equally frozen, and it was carrying the stale H.R. 5334 title live while the
// dated edition it duplicates had been annotated. The hub is now checked too.
//
// The count check originally matched only the literal string "N advanced a
// stage", one of four group labels. An edition made of "new to the site" or
// "signed into law" entries was never count-verified, and a page whose entry
// markup was restyled would parse ZERO entries and report clean. Both closed:
// all label forms are parsed, and zero entries parsed is now a failure.
//
// Usage: node scripts/verify-changelog.js   (exit 1 if anything is off)

'use strict';

const fs   = require('fs');
const path = require('path');

const ROOT  = path.join(__dirname, '..');
const cache = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'cache.json'), 'utf8'));
const bills = Array.isArray(cache.bills) ? cache.bills : Object.values(cache.bills || {});

// index by the id itself (slug in the href carries it)
const byId = {};
for (const b of bills) byId[String(b.id).toUpperCase()] = b;

function decode(s) {
  return String(s)
    .replace(/<[^>]*>/g, '')
    .replace(/&mdash;/g, '—').replace(/&ndash;/g, '–').replace(/&rarr;/g, '→')
    .replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, '&')
    .replace(/&middot;/g, '·').replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ').trim();
}

/** "/bill/119-hr-2069-stop-secret-spending-act-of-2025/" -> "119-HR-2069" */
function idFromHref(href) {
  const m = String(href).match(/\/bill\/(\d+)-([a-z]+)-(\d+)-/i);
  return m ? `${m[1]}-${m[2].toUpperCase()}-${m[3]}` : null;
}

/** Every entry <li> in a slice of markup, parsed. */
function parseEntries(html) {
  const found = [];
  for (const m of html.matchAll(/<li class="cl-entry">([\s\S]*?)<\/li>/g)) {
    const li = m[1];
    const hrefM  = li.match(/<a class="cl-code" href="([^"]+)"/);
    const codeM  = li.match(/<a class="cl-code"[^>]*>([\s\S]*?)<\/a>/);
    const titleM = li.match(/<span class="cl-title">([\s\S]*?)<\/span>/);
    const nowM   = li.match(/<span class="cl-renamed"[^>]*>\(now:\s*([\s\S]*?)\)<\/span>/);
    const transM = li.match(/<span class="cl-transition">([\s\S]*?)<\/span>\s*<span class="cl-meta">/);
    if (!codeM) continue;
    const trans = decode(transM ? transM[1] : '');
    const parts = trans.split('→').map(s => s.trim());
    found.push({
      href: hrefM ? hrefM[1] : '',
      id: hrefM ? idFromHref(hrefM[1]) : null,
      code: decode(codeM[1]),
      title: decode(titleM ? titleM[1] : ''),
      to: parts.length > 1 ? parts[1] : trans,
      nowTitle: nowM ? decode(nowM[1]) : null,
    });
  }
  return found;
}

/**
 * Every count the page states about itself, cross-checked against what it lists.
 *
 * Two shapes, both generated by generate_digest.js:
 *   subline  <p class="cl-edition-sub">Changes since the previous edition
 *              &middot; 4 signed into law &middot; 2 new to the site</p>
 *   group    <h3 class="cl-group-title">New to the site
 *              <span class="cl-group-count">3</span></h3>
 *
 * The old check hardcoded "N advanced a stage" -- one of four group labels
 * ("signed into law", "advanced a stage", "new to the site", "recent activity")
 * -- so most editions were never count-verified at all.
 */
function checkCounts(html, totalEntries) {
  const issues = [];

  // Per-group: header count vs entries inside that group's <section>.
  const groups = [];
  for (const g of html.matchAll(/<section class="cl-group">([\s\S]*?)<\/section>/g)) {
    const body  = g[1];
    const headM = body.match(/<h3 class="cl-group-title">([\s\S]*?)<span class="cl-group-count">(\d+)<\/span>/);
    if (!headM) { issues.push('a cl-group section has no parsable group header/count'); continue; }
    const label = decode(headM[1]).toLowerCase();
    const listed = (body.match(/<li class="cl-entry">/g) || []).length;
    groups.push({ label, claimed: Number(headM[2]), listed });
    if (Number(headM[2]) !== listed) {
      issues.push(`group "${label}" header says ${headM[2]}, ${listed} listed`);
    }
  }

  // Subline: every "<N> <label>" pair, whatever the label.
  const subM = html.match(/<p class="cl-edition-sub">([\s\S]*?)<\/p>/);
  if (!subM) {
    issues.push('no edition subline found (cl-edition-sub) — cannot count-verify the page');
  } else {
    const claims = [];
    for (const part of decode(subM[1]).split('·')) {
      const m = part.trim().match(/^(\d+)\s+(.+)$/);
      if (m) claims.push({ n: Number(m[1]), label: m[2].toLowerCase() });
    }
    if (!claims.length) {
      issues.push(`subline states no counts: "${decode(subM[1]).slice(0, 70)}"`);
    } else {
      const sum = claims.reduce((a, c) => a + c.n, 0);
      if (sum !== totalEntries) {
        issues.push(`subline totals ${sum} (${claims.map(c => `${c.n} ${c.label}`).join(', ')}), ${totalEntries} listed`);
      }
      // Each subline claim must name a real group and agree with its header.
      for (const c of claims) {
        const g = groups.find(x => x.label === c.label);
        if (!g) issues.push(`subline claims "${c.n} ${c.label}" but no such group section exists`);
        else if (g.claimed !== c.n) issues.push(`subline says ${c.n} ${c.label}, group header says ${g.claimed}`);
      }
    }
  }
  return issues;
}

/** Verify one changelog page. Returns { entries, problems }. */
function checkPage(label, file) {
  const html = fs.readFileSync(file, 'utf8');
  const found = parseEntries(html);
  let problems = 0, entries = 0;

  console.log(`\n── ${label}   ${found.length} entr${found.length === 1 ? 'y' : 'ies'}`);

  // ZERO entries parsed is a FAILURE, not a clean page. Every changelog page is
  // generated with at least one entry (generate_digest.js emits no edition when
  // nothing changed), so parsing none means the entry markup no longer matches
  // this script -- the gate silently checking nothing, which is the exact
  // failure mode this hardening pass exists to remove.
  if (!found.length) {
    console.log('  ❌ no entries parsed — entry markup no longer matches this checker');
    return { entries: 0, problems: 1 };
  }

  for (const issue of checkCounts(html, found.length)) {
    console.log(`  ❌ count mismatch — ${issue}`);
    problems++;
  }

  for (const e of found) {
    entries++;
    const bill = e.id ? byId[e.id.toUpperCase()] : null;
    if (!bill) { console.log(`  ❌ ${e.code}: id ${e.id || '?'} not in cache`); problems++; continue; }

    const issues = [];

    // TITLE is identity. A superseded title misidentifies the bill to a reader
    // TODAY -- H.R. 5334 went from an early-childhood education bill to a Russia
    // sanctions bill via a Senate text substitution, so the frozen title names
    // the wrong subject entirely. Flagged unless the entry already carries a
    // "now:" annotation pointing at the current title.
    if (e.title && bill.title && e.title !== bill.title && !e.nowTitle) {
      issues.push(`TITLE STALE\n        edition: "${e.title}"\n        current: "${bill.title}"`);
    } else if (e.nowTitle && e.nowTitle !== bill.title) {
      issues.push(`"now:" annotation is itself stale\n        says:    "${e.nowTitle}"\n        current: "${bill.title}"`);
    }

    // STAGE is deliberately NOT compared against the current record. A changelog
    // edition logs the transition as it stood that day; a bill advancing further
    // afterwards is the system working, not a defect. (Comparing them produced
    // false positives on H.R. 2069 and H.R. 6644, both of which simply advanced
    // again later.)
    // link must resolve on disk
    const rel = e.href.replace(/^\//, '');
    if (rel && !fs.existsSync(path.join(ROOT, rel, 'index.html')) && !fs.existsSync(path.join(ROOT, rel))) {
      issues.push(`link 404: ${e.href}`);
    }

    if (issues.length) { console.log(`  ❌ ${e.code}: ${issues.join('; ')}`); problems += issues.length; }
    else console.log(`  ✅ ${e.code} — ${e.title.slice(0, 50)}`);
  }

  return { entries, problems };
}

// ---------------------------------------------------------------------------
const dir = path.join(ROOT, 'changelog');

// The hub duplicates the latest edition in full and is just as frozen, so it
// gets the same treatment. It was the gap: readers land on /changelog/.
const pages = [];
if (fs.existsSync(path.join(dir, 'index.html'))) {
  pages.push({ label: 'index.html (hub)', file: path.join(dir, 'index.html') });
}
for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
  if (!e.isDirectory()) continue;
  const f = path.join(dir, e.name, 'index.html');
  if (fs.existsSync(f)) pages.push({ label: e.name, file: f });
}
pages.sort((a, b) => a.label.localeCompare(b.label));

let problems = 0, entries = 0;
for (const p of pages) {
  const r = checkPage(p.label, p.file);
  entries  += r.entries;
  problems += r.problems;
}

console.log('\n' + '═'.repeat(58));
if (!pages.length) {
  console.log('  ❌ no changelog pages found to verify');
  process.exit(1);
}
if (problems) {
  console.log(`  ❌ ${problems} problem(s) across ${entries} entr(ies) in ${pages.length} page(s)`);
  process.exit(1);
}
console.log(`  ✅ All ${entries} entr(ies) across ${pages.length} page(s) verify clean`);
